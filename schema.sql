CREATE DATABASE IF NOT EXISTS nba_veritabani
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE nba_veritabani;

-- LOOKUP TABLOLAR
CREATE TABLE Conference (
    ConferenceID INT AUTO_INCREMENT PRIMARY KEY,
    ConferenceName VARCHAR(100) UNIQUE NOT NULL
);

CREATE TABLE Position (
    PositionID INT AUTO_INCREMENT PRIMARY KEY,
    PositionName VARCHAR(50) UNIQUE NOT NULL,
    PositionAbbreviation VARCHAR(5) NOT NULL
);

CREATE TABLE SeasonType (
    SeasonTypeID INT AUTO_INCREMENT PRIMARY KEY,
    SeasonTypeName VARCHAR(50) UNIQUE NOT NULL
);

CREATE TABLE Season (
    SeasonID INT AUTO_INCREMENT PRIMARY KEY,
    SeasonYear VARCHAR(20) UNIQUE NOT NULL,
    StartDate DATE,
    EndDate DATE
);

-- TEMEL TABLOLAR
CREATE TABLE Team (
    TeamID INT PRIMARY KEY, 
    TeamName VARCHAR(255) NOT NULL,
    TeamAbbreviation VARCHAR(10) NOT NULL,
    City VARCHAR(100),
    FoundedYear INT,
    LogoURL VARCHAR(500),
    ConferenceID INT NOT NULL,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (ConferenceID) REFERENCES Conference(ConferenceID) ON DELETE RESTRICT ON UPDATE CASCADE,
    INDEX idx_conference (ConferenceID),
    INDEX idx_team_name (TeamName)
);

CREATE TABLE Player (
    PlayerID INT PRIMARY KEY, 
    PlayerName VARCHAR(255) NOT NULL,
    PositionID INT,
    DateOfBirth DATE,
    Height INT COMMENT 'Height in centimeters',
    Weight INT COMMENT 'Weight in kilograms',
    HeadshotURL VARCHAR(500),
    TeamID INT,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (PositionID) REFERENCES Position(PositionID) ON DELETE SET NULL ON UPDATE CASCADE,
    FOREIGN KEY (TeamID) REFERENCES Team(TeamID) ON DELETE SET NULL ON UPDATE CASCADE,
    INDEX idx_player_team (TeamID),
    INDEX idx_player_position (PositionID),
    INDEX idx_player_name (PlayerName),
    CHECK (Height IS NULL OR Height > 0),
    CHECK (Weight IS NULL OR Weight > 0)
);

-- İSTATİSTİK TABLOLARI
CREATE TABLE PlayerStats (
    PlayerStatsID INT AUTO_INCREMENT PRIMARY KEY,
    PlayerID INT NOT NULL,
    SeasonID INT NOT NULL,
    SeasonTypeID INT NOT NULL,
    GP INT NOT NULL DEFAULT 0,
    W INT NOT NULL DEFAULT 0,
    L INT NOT NULL DEFAULT 0,
    MIN DECIMAL(10, 2),
    FGM DECIMAL(10, 2),
    FGA DECIMAL(10, 2),
    FG_PCT DECIMAL(5, 3),
    FG3M DECIMAL(10, 2),
    FG3A DECIMAL(10, 2),
    FG3_PCT DECIMAL(5, 3),
    FTM DECIMAL(10, 2),
    FTA DECIMAL(10, 2),
    FT_PCT DECIMAL(5, 3),
    OREB DECIMAL(10, 2),
    DREB DECIMAL(10, 2),
    REB DECIMAL(10, 2),
    AST DECIMAL(10, 2),
    TOV DECIMAL(10, 2),
    STL DECIMAL(10, 2),
    BLK DECIMAL(10, 2),
    BLKA DECIMAL(10, 2),
    PF DECIMAL(10, 2),
    PFD DECIMAL(10, 2),
    PTS DECIMAL(10, 2),
    PLUS_MINUS DECIMAL(10, 2),
    Efficiency DECIMAL(10, 2),
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (PlayerID) REFERENCES Player(PlayerID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (SeasonID) REFERENCES Season(SeasonID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (SeasonTypeID) REFERENCES SeasonType(SeasonTypeID) ON DELETE RESTRICT ON UPDATE CASCADE,
    UNIQUE KEY unique_player_season (PlayerID, SeasonID, SeasonTypeID),
    INDEX idx_player_stats_player (PlayerID),
    INDEX idx_player_stats_season (SeasonID),
    INDEX idx_player_stats_season_type (SeasonTypeID),
    INDEX idx_player_stats_composite (PlayerID, SeasonID, SeasonTypeID),
    CHECK (GP >= 0),
    CHECK (W >= 0),
    CHECK (L >= 0),
    CHECK (MIN >= 0),
    CHECK (FGM >= 0),
    CHECK (FGA >= 0),
    CHECK (FG_PCT IS NULL OR (FG_PCT >= 0 AND FG_PCT <= 1)),
    CHECK (FG3_PCT IS NULL OR (FG3_PCT >= 0 AND FG3_PCT <= 1)),
    CHECK (FT_PCT IS NULL OR (FT_PCT >= 0 AND FT_PCT <= 1))
);

CREATE TABLE TeamStats (
    TeamStatsID INT AUTO_INCREMENT PRIMARY KEY,
    TeamID INT NOT NULL,
    SeasonID INT NOT NULL,
    GP INT NOT NULL DEFAULT 0,
    W INT NOT NULL DEFAULT 0,
    L INT NOT NULL DEFAULT 0,
    W_PCT DECIMAL(5, 3),
    MIN DECIMAL(10, 2),
    DEF_RATING DECIMAL(10, 2),
    DREB DECIMAL(10, 2),
    DREB_PCT DECIMAL(5, 3),
    STL DECIMAL(10, 2),
    BLK DECIMAL(10, 2),
    GP_RANK INT,
    W_RANK INT,
    L_RANK INT,
    W_PCT_RANK INT,
    MIN_RANK INT,
    DEF_RATING_RANK INT,
    DREB_RANK INT,
    DREB_PCT_RANK INT,
    STL_RANK INT,
    BLK_RANK INT,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (TeamID) REFERENCES Team(TeamID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (SeasonID) REFERENCES Season(SeasonID) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE KEY unique_team_season (TeamID, SeasonID),
    INDEX idx_team_stats_team (TeamID),
    INDEX idx_team_stats_season (SeasonID),
    CHECK (GP >= 0),
    CHECK (W >= 0),
    CHECK (L >= 0),
    CHECK (W_PCT IS NULL OR (W_PCT >= 0 AND W_PCT <= 1)),
    CHECK (DREB_PCT IS NULL OR (DREB_PCT >= 0 AND DREB_PCT <= 1)),
    CHECK (MIN >= 0)
);

CREATE TABLE OpponentStats (
    OpponentStatsID INT AUTO_INCREMENT PRIMARY KEY,
    TeamID INT NOT NULL,
    SeasonID INT NOT NULL,
    OPP_PTS_OFF_TOV DECIMAL(10, 2),
    OPP_PTS_2ND_CHANCE DECIMAL(10, 2),
    OPP_PTS_FB DECIMAL(10, 2),
    OPP_PTS_PAINT DECIMAL(10, 2),
    OPP_PTS_OFF_TOV_RANK INT,
    OPP_PTS_2ND_CHANCE_RANK INT,
    OPP_PTS_FB_RANK INT,
    OPP_PTS_PAINT_RANK INT,
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (TeamID) REFERENCES Team(TeamID) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (SeasonID) REFERENCES Season(SeasonID) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE KEY unique_opponent_team_season (TeamID, SeasonID),
    INDEX idx_opponent_stats_team (TeamID),
    INDEX idx_opponent_stats_season (SeasonID),
    CHECK (OPP_PTS_OFF_TOV >= 0),
    CHECK (OPP_PTS_2ND_CHANCE >= 0),
    CHECK (OPP_PTS_FB >= 0),
    CHECK (OPP_PTS_PAINT >= 0)
);

